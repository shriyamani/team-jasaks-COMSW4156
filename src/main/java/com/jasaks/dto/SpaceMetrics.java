package com.jasaks.dto;

import java.math.BigDecimal;

/**
 * Metric breakdown for a specific space in a report.
 *
 * @param spaceId the ID of the space
 * @param spaceName the name of the space
 * @param totalReservations total number of active/completed reservations
 * @param totalBookedHours total hours booked during the period
 * @param averageDurationHours average duration of bookings in hours
 * @param utilizationPercentage utilization percentage of available hours
 * @param peakBookingHour most frequent booking start hour
 * @param peakBookingDate most frequent booking date
 * @param averageGroupSize average group size of bookings
 * @param averageCapacityUsed average capacity percentage used by bookings
 * @param totalRevenue total revenue generated by bookings
 */
public record SpaceMetrics(
        Long spaceId,
        String spaceName,
        int totalReservations,
        double totalBookedHours,
        double averageDurationHours,
        double utilizationPercentage,
        String peakBookingHour,
        String peakBookingDate,
        double averageGroupSize,
        double averageCapacityUsed,
        BigDecimal totalRevenue
) {
}
